#!/usr/bin/env node
// wayback CLI.
//   wayback dev <project> [--port 3014] [--code-branches]
//     Runs the project's own Vite dev server with the timeline added, from a
//     wrapper config kept here. Nothing in the project is touched.
//   wayback init
//     Prints the two lines that add the timeline to a project's vite.config.
import fs from "node:fs"
import path from "node:path"
import { spawn } from "node:child_process"
import { fileURLToPath, pathToFileURL } from "node:url"

const HOME = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")
const CONFIGS = ["vite.config.ts", "vite.config.mts", "vite.config.js", "vite.config.mjs", "vite.config.cjs"]
const [cmd, ...rest] = process.argv.slice(2)

function flag(name, fallback) {
  const i = rest.indexOf(`--${name}`)
  if (i < 0) return fallback
  const value = rest[i + 1]
  rest.splice(i, 2)
  return value
}

function fail(msg) {
  console.error(`wayback: ${msg}`)
  process.exit(1)
}

function dev() {
  const port = Number(flag("port", 3014))
  const codeBranches = rest.includes("--code-branches")
  if (codeBranches) rest.splice(rest.indexOf("--code-branches"), 1)
  const project = path.resolve(rest[0] || ".")
  if (!fs.existsSync(path.join(project, "package.json"))) fail(`no package.json in ${project}`)
  // The project's own Vite if it has one (so its plugins match), else ours.
  const vite = [project, HOME].map((d) => path.join(d, "node_modules", "vite", "bin", "vite.js")).find((f) => fs.existsSync(f))
  if (!vite) fail(`vite isn't installed in ${project} (run npm install there first)`)
  const config = CONFIGS.map((f) => path.join(project, f)).find((f) => fs.existsSync(f))
  const name = path.basename(project)

  const work = path.join(HOME, ".cache", "projects", name)
  fs.mkdirSync(work, { recursive: true })
  const wrapper = path.join(work, "vite.config.mjs")
  const url = (p) => JSON.stringify(pathToFileURL(p).href)
  fs.writeFileSync(
    wrapper,
    `// Generated by wayback; regenerated on every run.
import { wayback } from ${url(path.join(HOME, "src", "plugin.js"))}
${config ? `import base from ${url(config)}` : "const base = {}"}

export default async (env) => {
  const cfg = (typeof base === "function" ? await base(env) : base) || {}
  return {
    ...cfg,
    root: cfg.root ? cfg.root : ${JSON.stringify(project)},
    // Our own dep cache, so the project's node_modules/.vite is left alone.
    cacheDir: ${JSON.stringify(path.join(work, "vite"))},
    plugins: [wayback({ codeBranches: ${codeBranches} }), ...(cfg.plugins || [])],
    server: { ...cfg.server, port: ${port}, strictPort: true },
  }
}
`,
  )
  console.log(`wayback: ${name} on http://localhost:${port}/`)
  const child = spawn(process.execPath, [vite, "--config", wrapper, ...rest.slice(1)], {
    cwd: project,
    stdio: "inherit",
    env: { ...process.env, VITE_CONFIG_NATIVE_IGNORE_WARNING: "true" },
  })
  child.on("exit", (code) => process.exit(code ?? 0))
  for (const sig of ["SIGINT", "SIGTERM"]) process.on(sig, () => child.kill(sig))
}

function init() {
  console.log(`Add to vite.config (dev only; it does nothing in builds):

  import { wayback } from "${path.join(HOME, "src", "plugin.js")}"

  plugins: [wayback(), /* …your plugins */],

Or leave the project untouched and run:  wayback dev <project>`)
}

if (cmd === "dev") dev()
else if (cmd === "init") init()
else {
  console.log(`Usage:
  wayback dev <project> [--port 3014] [--code-branches]
  wayback init`)
  process.exit(cmd ? 1 : 0)
}
